  static VitalityWeek _week(
    int number,
    VitalityProgramPhase phase,
    String titleEn,
    String titleAr,
    String focusEn,
    String focusAr,
    List<VitalityTask> tasks,
  ) =>
      VitalityWeek(
        weekNumber: number,
        phase: phase,
        titleEn: titleEn,
        titleAr: titleAr,
        focusEn: focusEn,
        focusAr: focusAr,
        dailyTasks: tasks,
        isUnlocked: number == 1,
      );

  static VitalityTask _task(
    String id,
    String titleEn,
    String titleAr,
    VitalityTaskCategory category,
  ) =>
      VitalityTask(
        id: id,
        titleEn: titleEn,
        titleAr: titleAr,
        category: category,
      );
